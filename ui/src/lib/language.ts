/** The Monaco language for a file path, by its base name; `plaintext` when unknown. */
export function languageFor(path: string): Language {
  const name = (path.split(/[\\/]/).pop() ?? path).toLowerCase();
  if (BY_NAME[name]) return BY_NAME[name];
  if (name.startsWith("dockerfile.") || name.startsWith("containerfile.")) return "dockerfile";
  const dot = name.lastIndexOf(".");
  if (dot <= 0) return BY_NAME[name] ?? "plaintext";
  return BY_EXT[name.slice(dot + 1)] ?? "plaintext";
}
